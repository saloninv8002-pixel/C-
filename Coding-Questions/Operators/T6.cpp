//Write a C++ program to perform arithmetic operations on two numbers.
#include<iostream>
using namespace std;
int main(){
	int a,b;
	cout<<"Enter two Numbers : ";
	cin>>a>>b;
	cout<<"Sum : "<<a+b<<endl;
	cout<<"Subtract : "<<a-b<<endl;
	cout<<"Multiplication : "<<a*b<<endl;
	cout<<"Division : "<<a/b<<endl;
	cout<<"Reminder : "<<a%b<<endl;
	return 0;
}
